import type { CommunityGroupSection } from '@luotianyi/shared';

export interface CommunityGroupSeed {
  name: string;
  number: string;
  level?: string;
  note?: string;
  section: CommunityGroupSection;
  sortOrder: number;
}

interface RawGroup {
  name: string;
  number: string;
  level?: string;
  note?: string;
}

const g = (name: string, number: string, level?: string, note?: string): RawGroup => ({
  name,
  number,
  level,
  note,
});

/** 按列出顺序自动生成 sortOrder（每项间隔 10，便于后台插空） */
function section(sectionId: CommunityGroupSection, rows: RawGroup[]): CommunityGroupSeed[] {
  return rows.map((row, index) => ({
    section: sectionId,
    name: row.name,
    number: row.number,
    level: row.level,
    note: row.note,
    sortOrder: index * 10,
  }));
}

